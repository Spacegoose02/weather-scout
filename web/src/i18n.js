let current = 'en';

export function pickLang(pref, browser = typeof navigator !== 'undefined' ? navigator.language : 'en') {
  if (pref === 'en' || pref === 'es') return pref;
  return /^es\b/i.test(browser || '') ? 'es' : 'en';
}

export function setLang(l) {
  current = l === 'es' ? 'es' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const lang = () => current;
// For toLocaleDateString / toLocaleTimeString: [] means "the browser's own".
export const locale = () => (current === 'es' ? 'es' : []);

// t('Feels like {temp}', { temp: '72°' })
export function t(en, vars) {
  let s = current === 'es' ? ES[en] ?? en : en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

